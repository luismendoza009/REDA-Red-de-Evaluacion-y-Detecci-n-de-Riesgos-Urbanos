-- Especialización 1:1 de reportes de tipo INCIDENTE.
-- Truco declarativo: la FK compuesta (id_reporte, tipo_reporte) -> reportes(id_reporte, tipo_reporte)
-- junto con CHECK (tipo_reporte = 'INCIDENTE') garantiza, sin triggers, que un incidente
-- solo puede colgar de un reporte marcado como INCIDENTE. Y como la FK no tiene
-- ON UPDATE CASCADE, tampoco se puede cambiar a CONDICION un reporte que ya tiene incidente.
-- Lo inverso (todo reporte INCIDENTE debe tener su fila aquí) no es expresable con
-- restricciones declarativas: se resolverá con un trigger de validación en la Entrega 3.
CREATE TABLE incidentes (
    id_incidente          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_reporte            INT           NOT NULL,
    tipo_reporte          VARCHAR(10)   NOT NULL DEFAULT 'INCIDENTE',
    id_entidad            INT,
    fecha_hecho           DATE          NOT NULL,
    tipo_dano             VARCHAR(15)   NOT NULL,
    descripcion_dano      TEXT          NOT NULL,
    hubo_atencion_medica  BOOLEAN       NOT NULL DEFAULT false,
    CONSTRAINT uq_incidentes_reporte UNIQUE (id_reporte),
    CONSTRAINT ck_incidentes_tipo_reporte CHECK (tipo_reporte = 'INCIDENTE'),
    CONSTRAINT ck_incidentes_tipo_dano CHECK (tipo_dano IN ('LESION', 'DANO_MATERIAL', 'AMBOS')),
    -- si no hubo lesión, no puede haber atención médica registrada
    CONSTRAINT ck_incidentes_atencion CHECK (NOT hubo_atencion_medica OR tipo_dano IN ('LESION', 'AMBOS')),
    CONSTRAINT ck_incidentes_descripcion CHECK (length(trim(descripcion_dano)) >= 10),
    CONSTRAINT fk_incidentes_reporte FOREIGN KEY (id_reporte, tipo_reporte)
        REFERENCES reportes (id_reporte, tipo_reporte) ON DELETE CASCADE,
    CONSTRAINT fk_incidentes_entidad FOREIGN KEY (id_entidad)
        REFERENCES entidades_publicas (id_entidad) ON DELETE RESTRICT
);
COMMENT ON TABLE  incidentes IS 'Daño sufrido por una persona o bien a causa de una falla (especialización 1:1 de reportes tipo INCIDENTE).';
COMMENT ON COLUMN incidentes.id_incidente IS 'Identificador único del incidente.';
COMMENT ON COLUMN incidentes.id_reporte IS 'Reporte de tipo INCIDENTE al que pertenece (1:1).';
COMMENT ON COLUMN incidentes.tipo_reporte IS 'Siempre INCIDENTE; existe solo para la FK compuesta que garantiza el tipo del reporte.';
COMMENT ON COLUMN incidentes.id_entidad IS 'Entidad a la que se atribuye presuntamente la falla (nulo si aún no se identifica).';
COMMENT ON COLUMN incidentes.fecha_hecho IS 'Día en que ocurrió el daño (puede ser anterior al reporte).';
COMMENT ON COLUMN incidentes.tipo_dano IS 'LESION, DANO_MATERIAL o AMBOS. [SENSIBLE] si incluye lesión.';
COMMENT ON COLUMN incidentes.descripcion_dano IS '[SENSIBLE] Descripción del daño; puede incluir información de salud. Protección: no visible al rol de análisis ni en el mapa público.';
COMMENT ON COLUMN incidentes.hubo_atencion_medica IS '[SENSIBLE] Si la persona recibió atención médica (dato de salud).';

CREATE TABLE testigos (
    id_testigo    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_incidente  INT           NOT NULL,
    nombre        VARCHAR(120)  NOT NULL,
    contacto      VARCHAR(150)  NOT NULL,
    CONSTRAINT uq_testigos_incidente_nombre UNIQUE (id_incidente, nombre),
    CONSTRAINT fk_testigos_incidente FOREIGN KEY (id_incidente) REFERENCES incidentes (id_incidente) ON DELETE CASCADE
);
COMMENT ON TABLE  testigos IS 'Personas que presenciaron el incidente (fortalecen el caso).';
COMMENT ON COLUMN testigos.id_testigo IS 'Identificador único del testigo.';
COMMENT ON COLUMN testigos.id_incidente IS 'Incidente que presenció.';
COMMENT ON COLUMN testigos.nombre IS '[PERSONAL] Nombre del testigo. Protección: solo visible para operador y abogado del caso.';
COMMENT ON COLUMN testigos.contacto IS '[PERSONAL] Teléfono o correo del testigo. Protección: solo visible para operador y abogado del caso.';
