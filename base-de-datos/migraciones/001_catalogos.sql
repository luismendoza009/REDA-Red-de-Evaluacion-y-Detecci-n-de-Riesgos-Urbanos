-- Tablas catálogo: no dependen de ninguna otra tabla.
-- Convención de etiquetas en los comentarios (las usa el diccionario de datos):
--   [PERSONAL]  dato personal (Ley 1581 de 2012)
--   [SENSIBLE]  dato sensible (salud)
--   [SIMULADO]  valor simulado para el proyecto de aula, no proviene de una fuente real
-- =============================================================================

-- Roles de la aplicación (no confundir con roles de PostgreSQL, que llegan en la Entrega 3).
CREATE TABLE roles (
    id_rol  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre  VARCHAR(30) NOT NULL,
    CONSTRAINT uq_roles_nombre UNIQUE (nombre),
    CONSTRAINT ck_roles_nombre CHECK (nombre IN ('CIUDADANO', 'OPERADOR', 'ABOGADO', 'ADMINISTRADOR', 'ANALISTA'))
);
COMMENT ON TABLE  roles IS 'Catálogo de roles de la aplicación (Ciudadano, Operador, Abogado, Administrador, Analista).';
COMMENT ON COLUMN roles.id_rol IS 'Identificador único del rol.';
COMMENT ON COLUMN roles.nombre IS 'Nombre del rol en mayúsculas; lista cerrada controlada por CHECK.';

CREATE TABLE categorias (
    id_categoria  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre        VARCHAR(80) NOT NULL,
    descripcion   TEXT,
    CONSTRAINT uq_categorias_nombre UNIQUE (nombre)
);
COMMENT ON TABLE  categorias IS 'Tipos de falla de infraestructura que puede clasificar un reporte (hueco, alcantarilla, luminaria...).';
COMMENT ON COLUMN categorias.id_categoria IS 'Identificador único de la categoría.';
COMMENT ON COLUMN categorias.nombre IS 'Nombre de la categoría (único).';
COMMENT ON COLUMN categorias.descripcion IS 'Qué tipo de falla cubre la categoría.';

-- Zonas: barrios de la ciudad. Las columnas de contexto alimentan el IRU (Entrega 3).
-- Cambio respecto a la Entrega 1: se agregan ciudad, UNIQUE(nombre, ciudad), CHECK de tipo
-- y las variables de contexto de la zona (simuladas).
CREATE TABLE zonas (
    id_zona                 INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre                  VARCHAR(100) NOT NULL,
    tipo                    VARCHAR(20)  NOT NULL,
    ciudad                  VARCHAR(80)  NOT NULL DEFAULT 'Valledupar',
    nivel_trafico           SMALLINT     NOT NULL DEFAULT 3,
    centros_educativos      SMALLINT     NOT NULL DEFAULT 0,
    centros_salud           SMALLINT     NOT NULL DEFAULT 0,
    CONSTRAINT uq_zonas_nombre_ciudad UNIQUE (nombre, ciudad),
    CONSTRAINT ck_zonas_tipo CHECK (tipo IN ('RESIDENCIAL', 'COMERCIAL', 'ESCOLAR', 'MIXTA', 'INSTITUCIONAL')),
    CONSTRAINT ck_zonas_trafico CHECK (nivel_trafico BETWEEN 1 AND 5),
    CONSTRAINT ck_zonas_educativos CHECK (centros_educativos >= 0),
    CONSTRAINT ck_zonas_salud CHECK (centros_salud >= 0)
);
COMMENT ON TABLE  zonas IS 'Barrios o zonas de la ciudad; permiten agregar reportes y aportan variables de contexto al IRU.';
COMMENT ON COLUMN zonas.id_zona IS 'Identificador único de la zona.';
COMMENT ON COLUMN zonas.nombre IS 'Nombre del barrio o zona (único dentro de la ciudad).';
COMMENT ON COLUMN zonas.tipo IS 'Uso predominante: RESIDENCIAL, COMERCIAL, ESCOLAR, MIXTA o INSTITUCIONAL.';
COMMENT ON COLUMN zonas.ciudad IS 'Ciudad a la que pertenece la zona (el sistema está pensado para escalar a otras ciudades).';
COMMENT ON COLUMN zonas.nivel_trafico IS '[SIMULADO] Nivel de tráfico vehicular/peatonal de 1 (bajo) a 5 (muy alto).';
COMMENT ON COLUMN zonas.centros_educativos IS '[SIMULADO] Número de colegios o centros educativos en la zona.';
COMMENT ON COLUMN zonas.centros_salud IS '[SIMULADO] Número de hospitales, clínicas o centros de salud en la zona.';

-- Estados del REPORTE (ciclo de atención de la falla).
CREATE TABLE estados (
    id_estado  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre     VARCHAR(30) NOT NULL,
    CONSTRAINT uq_estados_nombre UNIQUE (nombre)
);
COMMENT ON TABLE  estados IS 'Catálogo de estados de un reporte: Pendiente, En revisión, Validado, En proceso, Solucionado, Rechazado.';
COMMENT ON COLUMN estados.id_estado IS 'Identificador único del estado.';
COMMENT ON COLUMN estados.nombre IS 'Nombre del estado (único).';

-- Estados del CASO legal. Es un catálogo distinto de "estados" porque el ciclo de vida
-- de un caso (Borrador -> Remitido -> Aceptado...) no tiene nada que ver con el de la falla.
CREATE TABLE estados_caso (
    id_estado_caso  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR(40) NOT NULL,
    CONSTRAINT uq_estados_caso_nombre UNIQUE (nombre)
);
COMMENT ON TABLE  estados_caso IS 'Catálogo de estados de un caso legal: Borrador, Evaluado, Remitido, Aceptado por abogado, Rechazado, Cerrado.';
COMMENT ON COLUMN estados_caso.id_estado_caso IS 'Identificador único del estado de caso.';
COMMENT ON COLUMN estados_caso.nombre IS 'Nombre del estado de caso (único).';

-- Entidades públicas a las que se atribuye la falla (posible demandado).
CREATE TABLE entidades_publicas (
    id_entidad  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(150) NOT NULL,
    tipo        VARCHAR(30)  NOT NULL,
    ciudad      VARCHAR(80)  NOT NULL DEFAULT 'Valledupar',
    CONSTRAINT uq_entidades_nombre UNIQUE (nombre),
    CONSTRAINT ck_entidades_tipo CHECK (tipo IN ('ALCALDIA', 'SECRETARIA', 'EMPRESA_SERVICIOS', 'GOBERNACION', 'NACIONAL', 'OTRA'))
);
COMMENT ON TABLE  entidades_publicas IS 'Entidades a las que se atribuye la responsabilidad de mantener la infraestructura (posible parte demandada).';
COMMENT ON COLUMN entidades_publicas.id_entidad IS 'Identificador único de la entidad.';
COMMENT ON COLUMN entidades_publicas.nombre IS 'Nombre oficial de la entidad (único).';
COMMENT ON COLUMN entidades_publicas.tipo IS 'ALCALDIA, SECRETARIA, EMPRESA_SERVICIOS, GOBERNACION, NACIONAL u OTRA.';
COMMENT ON COLUMN entidades_publicas.ciudad IS 'Ciudad de jurisdicción de la entidad.';
