-- =============================================================================
-- 003_reportes.sql
-- Núcleo: reportes y sus tablas dependientes.
-- Política de borrado:
--   RESTRICT hacia catálogos y usuarios: un reporte es evidencia histórica y no puede
--            quedar huérfano ni desaparecer porque se borre su categoría, zona o autor.
--   CASCADE  en hijos que no tienen sentido sin el reporte (evidencias, evaluaciones,
--            historial, relaciones).
-- =============================================================================

-- Cambios respecto a la Entrega 1:
--   * tipo_reporte: CONDICION (antecedente) o INCIDENTE (hubo daño). Nuevo enfoque del negocio.
--   * fecha -> fecha_reporte DATE (nombre más claro).
--   * CHECK de rango para latitud/longitud.
--   * UNIQUE (id_reporte, tipo_reporte): permite que "incidentes" referencie solo
--     reportes de tipo INCIDENTE con una FK compuesta (ver 004).
CREATE TABLE reportes (
    id_reporte      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario      INT            NOT NULL,
    id_categoria    INT            NOT NULL,
    id_zona         INT            NOT NULL,
    id_estado       INT            NOT NULL,
    tipo_reporte    VARCHAR(10)    NOT NULL DEFAULT 'CONDICION',
    descripcion     TEXT           NOT NULL,
    latitud         NUMERIC(9,6)   NOT NULL,
    longitud        NUMERIC(9,6)   NOT NULL,
    fecha_reporte   DATE           NOT NULL DEFAULT CURRENT_DATE,
    nivel_gravedad  SMALLINT,
    CONSTRAINT uq_reportes_id_tipo UNIQUE (id_reporte, tipo_reporte),
    CONSTRAINT ck_reportes_tipo CHECK (tipo_reporte IN ('CONDICION', 'INCIDENTE')),
    CONSTRAINT ck_reportes_descripcion CHECK (length(trim(descripcion)) >= 10),
    CONSTRAINT ck_reportes_latitud CHECK (latitud BETWEEN -90 AND 90),
    CONSTRAINT ck_reportes_longitud CHECK (longitud BETWEEN -180 AND 180),
    CONSTRAINT ck_reportes_gravedad CHECK (nivel_gravedad BETWEEN 1 AND 5),
    CONSTRAINT fk_reportes_usuario   FOREIGN KEY (id_usuario)   REFERENCES usuarios   (id_usuario)   ON DELETE RESTRICT,
    CONSTRAINT fk_reportes_categoria FOREIGN KEY (id_categoria) REFERENCES categorias (id_categoria) ON DELETE RESTRICT,
    CONSTRAINT fk_reportes_zona      FOREIGN KEY (id_zona)      REFERENCES zonas      (id_zona)      ON DELETE RESTRICT,
    CONSTRAINT fk_reportes_estado    FOREIGN KEY (id_estado)    REFERENCES estados    (id_estado)    ON DELETE RESTRICT
);
COMMENT ON TABLE  reportes IS 'Entidad central: cada falla de infraestructura reportada. CONDICION = antecedente sin daño; INCIDENTE = hubo daño a una persona o bien.';
COMMENT ON COLUMN reportes.id_reporte IS 'Identificador único del reporte.';
COMMENT ON COLUMN reportes.id_usuario IS 'Ciudadano que creó el reporte.';
COMMENT ON COLUMN reportes.id_categoria IS 'Categoría de la falla.';
COMMENT ON COLUMN reportes.id_zona IS 'Barrio o zona donde está la falla.';
COMMENT ON COLUMN reportes.id_estado IS 'Estado actual del reporte (el historial queda en historial_estados).';
COMMENT ON COLUMN reportes.tipo_reporte IS 'CONDICION (antecedente probatorio) o INCIDENTE (hubo daño; tiene fila en incidentes).';
COMMENT ON COLUMN reportes.descripcion IS 'Descripción libre de la falla (mínimo 10 caracteres).';
COMMENT ON COLUMN reportes.latitud IS 'Latitud GPS (WGS84) de la falla. En el mapa público se muestra sin datos del autor.';
COMMENT ON COLUMN reportes.longitud IS 'Longitud GPS (WGS84) de la falla.';
COMMENT ON COLUMN reportes.fecha_reporte IS 'Día en que se registró el reporte.';
COMMENT ON COLUMN reportes.nivel_gravedad IS 'Gravedad percibida por el ciudadano, 1 a 5 (opcional). No es el IRU.';

-- Cambio respecto a la Entrega 1: se agregan metadatos de la evidencia (tipo, tamaño,
-- hash SHA-256 y fecha de captura). El hash permite demostrar después que el archivo
-- no fue alterado desde que se cargó, lo que fortalece su valor probatorio.
CREATE TABLE evidencias (
    id_evidencia   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_reporte     INT           NOT NULL,
    ruta_imagen    VARCHAR(255)  NOT NULL,
    tipo_mime      VARCHAR(30)   NOT NULL,
    tamano_bytes   INT           NOT NULL,
    hash_sha256    CHAR(64)      NOT NULL,
    fecha_captura  DATE,
    fecha_carga    DATE          NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT uq_evidencias_ruta UNIQUE (ruta_imagen),
    CONSTRAINT uq_evidencias_hash UNIQUE (hash_sha256),
    CONSTRAINT ck_evidencias_mime CHECK (tipo_mime IN ('image/jpeg', 'image/png', 'image/webp')),
    CONSTRAINT ck_evidencias_tamano CHECK (tamano_bytes > 0 AND tamano_bytes <= 10485760),
    CONSTRAINT ck_evidencias_hash CHECK (hash_sha256 ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_evidencias_fechas CHECK (fecha_captura IS NULL OR fecha_captura <= fecha_carga),
    CONSTRAINT fk_evidencias_reporte FOREIGN KEY (id_reporte) REFERENCES reportes (id_reporte) ON DELETE CASCADE
);
COMMENT ON TABLE  evidencias IS 'Fotografías de soporte de un reporte (1 reporte : N evidencias).';
COMMENT ON COLUMN evidencias.id_evidencia IS 'Identificador único de la evidencia.';
COMMENT ON COLUMN evidencias.id_reporte IS 'Reporte al que pertenece la evidencia.';
COMMENT ON COLUMN evidencias.ruta_imagen IS 'Ruta relativa del archivo en el servidor, con nombre generado (no el original).';
COMMENT ON COLUMN evidencias.tipo_mime IS 'Tipo de archivo permitido: image/jpeg, image/png o image/webp.';
COMMENT ON COLUMN evidencias.tamano_bytes IS 'Tamaño del archivo en bytes (máximo 10 MB).';
COMMENT ON COLUMN evidencias.hash_sha256 IS 'Huella SHA-256 del archivo; prueba de integridad y evita cargar la misma foto dos veces.';
COMMENT ON COLUMN evidencias.fecha_captura IS 'Fecha de toma de la foto según sus metadatos (si existen). [PERSONAL] Los metadatos EXIF pueden revelar ubicación.';
COMMENT ON COLUMN evidencias.fecha_carga IS 'Día en que se subió la foto a la plataforma.';

-- Cambio respecto a la Entrega 1: se registra qué operador evaluó (id_usuario).
CREATE TABLE evaluaciones (
    id_evaluacion     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_reporte        INT          NOT NULL,
    id_usuario        INT          NOT NULL,
    gravedad          SMALLINT,
    impacto           SMALLINT,
    frecuencia        SMALLINT,
    fecha_evaluacion  DATE         NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT ck_evaluaciones_gravedad   CHECK (gravedad   BETWEEN 0 AND 100),
    CONSTRAINT ck_evaluaciones_impacto    CHECK (impacto    BETWEEN 0 AND 100),
    CONSTRAINT ck_evaluaciones_frecuencia CHECK (frecuencia BETWEEN 0 AND 100),
    CONSTRAINT ck_evaluaciones_alguna CHECK (num_nonnulls(gravedad, impacto, frecuencia) > 0),
    CONSTRAINT fk_evaluaciones_reporte FOREIGN KEY (id_reporte) REFERENCES reportes (id_reporte) ON DELETE CASCADE,
    CONSTRAINT fk_evaluaciones_usuario FOREIGN KEY (id_usuario) REFERENCES usuarios (id_usuario) ON DELETE RESTRICT
);
COMMENT ON TABLE  evaluaciones IS 'Evaluación técnica de un reporte hecha por un operador; insumo del IRU.';
COMMENT ON COLUMN evaluaciones.id_evaluacion IS 'Identificador único de la evaluación.';
COMMENT ON COLUMN evaluaciones.id_reporte IS 'Reporte evaluado.';
COMMENT ON COLUMN evaluaciones.id_usuario IS 'Operador que hizo la evaluación.';
COMMENT ON COLUMN evaluaciones.gravedad IS 'Gravedad técnica 0-100.';
COMMENT ON COLUMN evaluaciones.impacto IS 'Impacto potencial 0-100 (personas/vehículos expuestos).';
COMMENT ON COLUMN evaluaciones.frecuencia IS 'Recurrencia del problema 0-100.';
COMMENT ON COLUMN evaluaciones.fecha_evaluacion IS 'Fecha de la evaluación.';

CREATE TABLE historial_estados (
    id_historial        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_reporte          INT          NOT NULL,
    id_estado_anterior  INT          NOT NULL,
    id_estado_nuevo     INT          NOT NULL,
    id_usuario          INT          NOT NULL,
    fecha_cambio        DATE         NOT NULL DEFAULT CURRENT_DATE,
    observacion         TEXT,
    CONSTRAINT ck_historial_distintos CHECK (id_estado_anterior <> id_estado_nuevo),
    CONSTRAINT fk_historial_reporte  FOREIGN KEY (id_reporte)         REFERENCES reportes (id_reporte) ON DELETE CASCADE,
    CONSTRAINT fk_historial_anterior FOREIGN KEY (id_estado_anterior) REFERENCES estados  (id_estado)  ON DELETE RESTRICT,
    CONSTRAINT fk_historial_nuevo    FOREIGN KEY (id_estado_nuevo)    REFERENCES estados  (id_estado)  ON DELETE RESTRICT,
    CONSTRAINT fk_historial_usuario  FOREIGN KEY (id_usuario)         REFERENCES usuarios (id_usuario) ON DELETE RESTRICT
);
COMMENT ON TABLE  historial_estados IS 'Bitácora de cada cambio de estado de un reporte: quién, cuándo, de qué estado a cuál y por qué.';
COMMENT ON COLUMN historial_estados.id_historial IS 'Identificador único del registro.';
COMMENT ON COLUMN historial_estados.id_reporte IS 'Reporte cuyo estado cambió.';
COMMENT ON COLUMN historial_estados.id_estado_anterior IS 'Estado antes del cambio.';
COMMENT ON COLUMN historial_estados.id_estado_nuevo IS 'Estado después del cambio (distinto del anterior).';
COMMENT ON COLUMN historial_estados.id_usuario IS 'Operador o administrador que hizo el cambio.';
COMMENT ON COLUMN historial_estados.fecha_cambio IS 'Día del cambio de estado.';
COMMENT ON COLUMN historial_estados.observacion IS 'Justificación u observación del cambio.';

-- Cambio respecto a la Entrega 1: se distingue el tipo de relación.
--   SIMILAR     : dos reportes del mismo problema (duplicados o cercanos).
--   ANTECEDENTE : id_reporte es un INCIDENTE e id_reporte_relacionado es una CONDICION
--                 previa en el mismo punto. Es la función estrella: "la entidad ya sabía".
CREATE TABLE reportes_relacionados (
    id_reporte              INT          NOT NULL,
    id_reporte_relacionado  INT          NOT NULL,
    tipo_relacion           VARCHAR(12)  NOT NULL DEFAULT 'SIMILAR',
    origen                  VARCHAR(10)  NOT NULL DEFAULT 'AUTOMATICO',
    fecha_vinculo           DATE         NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT pk_reportes_relacionados PRIMARY KEY (id_reporte, id_reporte_relacionado),
    CONSTRAINT ck_relacionados_distintos CHECK (id_reporte <> id_reporte_relacionado),
    CONSTRAINT ck_relacionados_tipo CHECK (tipo_relacion IN ('SIMILAR', 'ANTECEDENTE')),
    CONSTRAINT ck_relacionados_origen CHECK (origen IN ('AUTOMATICO', 'MANUAL')),
    CONSTRAINT fk_relacionados_reporte     FOREIGN KEY (id_reporte)             REFERENCES reportes (id_reporte) ON DELETE CASCADE,
    CONSTRAINT fk_relacionados_relacionado FOREIGN KEY (id_reporte_relacionado) REFERENCES reportes (id_reporte) ON DELETE CASCADE
);
COMMENT ON TABLE  reportes_relacionados IS 'Relación M:N reflexiva entre reportes: similares o antecedentes de un incidente.';
COMMENT ON COLUMN reportes_relacionados.id_reporte IS 'Reporte origen (en ANTECEDENTE, el incidente).';
COMMENT ON COLUMN reportes_relacionados.id_reporte_relacionado IS 'Reporte vinculado (en ANTECEDENTE, la condición previa).';
COMMENT ON COLUMN reportes_relacionados.tipo_relacion IS 'SIMILAR o ANTECEDENTE.';
COMMENT ON COLUMN reportes_relacionados.origen IS 'AUTOMATICO (lo calculó el sistema por cercanía) o MANUAL (lo vinculó un operador).';
COMMENT ON COLUMN reportes_relacionados.fecha_vinculo IS 'Día en que se creó el vínculo.';
