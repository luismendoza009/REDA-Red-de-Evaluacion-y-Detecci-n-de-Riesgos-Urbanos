-- =============================================================================
-- 006_indices_priorizacion.sql
-- Estructuras para los índices IRU (riesgo urbano) e IVC (viabilidad del caso).
-- Los dos índices se mantienen SEPARADOS a propósito: mezclar riesgo objetivo con
-- rentabilidad de litigar en un solo número sería un conflicto de interés.
-- El cálculo (funciones PL/pgSQL) llega en la Entrega 3; aquí solo las tablas.
-- =============================================================================

-- Cada índice tiene versiones de su configuración (pesos + umbrales de nivel).
-- Se separa de parametros_indice por normalización: "vigente" y los umbrales dependen
-- de la versión (nombre_indice, numero_version), no de cada variable. Si estuvieran en
-- parametros_indice habría una dependencia parcial de la clave (violación de 2FN).
CREATE TABLE versiones_indice (
    id_version       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_indice    VARCHAR(3)    NOT NULL,
    numero_version   SMALLINT      NOT NULL,
    descripcion      TEXT          NOT NULL,
    umbral_medio     NUMERIC(5,2)  NOT NULL DEFAULT 25,
    umbral_alto      NUMERIC(5,2)  NOT NULL DEFAULT 50,
    umbral_critico   NUMERIC(5,2)  NOT NULL DEFAULT 75,
    vigente          BOOLEAN       NOT NULL DEFAULT false,
    fecha_creacion   TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT uq_versiones_indice UNIQUE (nombre_indice, numero_version),
    CONSTRAINT ck_versiones_nombre CHECK (nombre_indice IN ('IRU', 'IVC')),
    CONSTRAINT ck_versiones_numero CHECK (numero_version >= 1),
    CONSTRAINT ck_versiones_umbrales CHECK (0 < umbral_medio AND umbral_medio < umbral_alto
                                            AND umbral_alto < umbral_critico AND umbral_critico <= 100)
);
-- Solo una versión vigente por índice (restricción declarativa con índice único parcial).
CREATE UNIQUE INDEX uq_versiones_una_vigente ON versiones_indice (nombre_indice) WHERE vigente;

COMMENT ON TABLE  versiones_indice IS 'Versiones de configuración de cada índice (IRU o IVC): umbrales de nivel y cuál está vigente.';
COMMENT ON COLUMN versiones_indice.id_version IS 'Identificador único de la versión.';
COMMENT ON COLUMN versiones_indice.nombre_indice IS 'IRU (Índice de Riesgo Urbano) o IVC (Índice de Viabilidad del Caso).';
COMMENT ON COLUMN versiones_indice.numero_version IS 'Número de versión, consecutivo por índice.';
COMMENT ON COLUMN versiones_indice.descripcion IS 'Qué cambió en esta versión y de dónde salen los pesos.';
COMMENT ON COLUMN versiones_indice.umbral_medio IS 'Desde este puntaje el nivel es MEDIO (preliminar, por calibrar).';
COMMENT ON COLUMN versiones_indice.umbral_alto IS 'Desde este puntaje el nivel es ALTO (preliminar, por calibrar).';
COMMENT ON COLUMN versiones_indice.umbral_critico IS 'Desde este puntaje el nivel es CRÍTICO (preliminar, por calibrar).';
COMMENT ON COLUMN versiones_indice.vigente IS 'true = versión usada en los cálculos nuevos. Máximo una por índice.';
COMMENT ON COLUMN versiones_indice.fecha_creacion IS 'Momento de creación de la versión.';

-- Peso de cada variable dentro de una versión. Índice = Σ (peso_i × valor_i), con Σ pesos = 1.
-- Que los pesos de una versión sumen 1 es una regla entre filas: no se puede con CHECK;
-- se validará con trigger en la Entrega 3.
CREATE TABLE parametros_indice (
    id_version   INT           NOT NULL,
    variable     VARCHAR(40)   NOT NULL,
    peso         NUMERIC(5,4)  NOT NULL,
    descripcion  TEXT          NOT NULL,
    CONSTRAINT pk_parametros_indice PRIMARY KEY (id_version, variable),
    CONSTRAINT ck_parametros_peso CHECK (peso > 0 AND peso <= 1),
    CONSTRAINT ck_parametros_variable CHECK (variable ~ '^[a-z_]+$'),
    CONSTRAINT fk_parametros_version FOREIGN KEY (id_version) REFERENCES versiones_indice (id_version) ON DELETE CASCADE
);
COMMENT ON TABLE  parametros_indice IS 'Peso de cada variable en una versión de índice (configurable y versionado).';
COMMENT ON COLUMN parametros_indice.id_version IS 'Versión del índice a la que pertenece el peso.';
COMMENT ON COLUMN parametros_indice.variable IS 'Nombre técnico de la variable (snake_case), p. ej. antecedentes_previos.';
COMMENT ON COLUMN parametros_indice.peso IS 'Peso de la variable, en (0, 1]. Los pesos de una versión deben sumar 1.';
COMMENT ON COLUMN parametros_indice.descripcion IS 'Qué mide la variable y cómo se normaliza a 0-100.';

-- Resultado de cada cálculo, con su desglose por variable para poder explicarlo.
-- Se guarda el histórico (no se sobrescribe): permite ver cómo cambió el índice de un reporte.
CREATE TABLE calculos_indice (
    id_calculo     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_reporte     INT           NOT NULL,
    id_version     INT           NOT NULL,
    valor          NUMERIC(5,2)  NOT NULL,
    desglose       JSONB         NOT NULL,
    fecha_calculo  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT ck_calculos_valor CHECK (valor BETWEEN 0 AND 100),
    CONSTRAINT ck_calculos_desglose CHECK (jsonb_typeof(desglose) = 'object'),
    CONSTRAINT fk_calculos_reporte FOREIGN KEY (id_reporte) REFERENCES reportes         (id_reporte) ON DELETE CASCADE,
    CONSTRAINT fk_calculos_version FOREIGN KEY (id_version) REFERENCES versiones_indice (id_version) ON DELETE RESTRICT
);
COMMENT ON TABLE  calculos_indice IS 'Historial de cálculos de IRU/IVC por reporte, con el desglose de razones.';
COMMENT ON COLUMN calculos_indice.id_calculo IS 'Identificador único del cálculo.';
COMMENT ON COLUMN calculos_indice.id_reporte IS 'Reporte calculado (IRU para condiciones e incidentes; IVC solo para incidentes).';
COMMENT ON COLUMN calculos_indice.id_version IS 'Versión de parámetros usada (de ahí sale si es IRU o IVC).';
COMMENT ON COLUMN calculos_indice.valor IS 'Puntaje total 0-100. El nivel (Bajo/Medio/Alto/Crítico) se deriva con los umbrales de la versión, no se almacena.';
COMMENT ON COLUMN calculos_indice.desglose IS 'JSON {variable: {valor_normalizado, peso, aporte}} para explicar el resultado.';
COMMENT ON COLUMN calculos_indice.fecha_calculo IS 'Momento del cálculo.';
