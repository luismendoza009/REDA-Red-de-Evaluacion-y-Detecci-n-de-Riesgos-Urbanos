-- Un caso nace de UN incidente que un operador consideró viable (1:1 con incidentes).
-- Nota de diseño: el índice de viabilidad (IVC) NO se guarda aquí como columna. Es un valor
-- derivado de muchas tablas; guardarlo en casos rompería la 3FN y perdería el historial y el
-- desglose. Se guarda en calculos_indice (006), versionado y con sus razones.
CREATE TABLE casos (
    id_caso         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_incidente    INT          NOT NULL,
    id_estado_caso  INT          NOT NULL,
    id_operador     INT          NOT NULL,
    fecha_creacion  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    fecha_cierre    TIMESTAMPTZ,
    observacion     TEXT,
    CONSTRAINT uq_casos_incidente UNIQUE (id_incidente),
    CONSTRAINT ck_casos_fechas CHECK (fecha_cierre IS NULL OR fecha_cierre >= fecha_creacion),
    -- RESTRICT: un caso con remisiones cobradas es registro contable; no se borra en cascada
    CONSTRAINT fk_casos_incidente FOREIGN KEY (id_incidente)   REFERENCES incidentes   (id_incidente)   ON DELETE RESTRICT,
    CONSTRAINT fk_casos_estado    FOREIGN KEY (id_estado_caso) REFERENCES estados_caso (id_estado_caso) ON DELETE RESTRICT,
    CONSTRAINT fk_casos_operador  FOREIGN KEY (id_operador)    REFERENCES usuarios     (id_usuario)     ON DELETE RESTRICT
);
COMMENT ON TABLE  casos IS 'Expediente legal creado a partir de un incidente viable (1:1 con incidentes).';
COMMENT ON COLUMN casos.id_caso IS 'Identificador único del caso.';
COMMENT ON COLUMN casos.id_incidente IS 'Incidente que origina el caso (UNIQUE: un incidente, un caso).';
COMMENT ON COLUMN casos.id_estado_caso IS 'Estado actual del caso.';
COMMENT ON COLUMN casos.id_operador IS 'Operador que validó el incidente y abrió el caso.';
COMMENT ON COLUMN casos.fecha_creacion IS 'Momento en que se abrió el caso.';
COMMENT ON COLUMN casos.fecha_cierre IS 'Momento de cierre (nulo mientras está abierto).';
COMMENT ON COLUMN casos.observacion IS 'Notas internas del operador sobre el caso.';

-- Remisión = envío de un caso a un abogado. Es lo que se factura (cuota fija por lead).
-- No es cuota litis ni participación en honorarios (ver riesgos legales en la documentación).
CREATE TABLE remisiones (
    id_remision      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_caso          INT            NOT NULL,
    id_abogado       INT            NOT NULL,
    fecha_envio      TIMESTAMPTZ    NOT NULL DEFAULT now(),
    estado_remision  VARCHAR(10)    NOT NULL DEFAULT 'ENVIADA',
    fecha_respuesta  TIMESTAMPTZ,
    motivo_rechazo   TEXT,
    valor_cobrado    NUMERIC(12,2)  NOT NULL,
    CONSTRAINT uq_remisiones_caso_abogado UNIQUE (id_caso, id_abogado),
    CONSTRAINT ck_remisiones_estado CHECK (estado_remision IN ('ENVIADA', 'ACEPTADA', 'RECHAZADA', 'VENCIDA')),
    CONSTRAINT ck_remisiones_valor CHECK (valor_cobrado >= 0),
    -- coherencia entre estado y fechas: una remisión respondida tiene fecha de respuesta y viceversa
    CONSTRAINT ck_remisiones_respuesta CHECK (
        (estado_remision IN ('ENVIADA', 'VENCIDA') AND fecha_respuesta IS NULL) OR
        (estado_remision IN ('ACEPTADA', 'RECHAZADA') AND fecha_respuesta IS NOT NULL AND fecha_respuesta >= fecha_envio)
    ),
    CONSTRAINT ck_remisiones_motivo CHECK (motivo_rechazo IS NULL OR estado_remision = 'RECHAZADA'),
    CONSTRAINT fk_remisiones_caso    FOREIGN KEY (id_caso)    REFERENCES casos    (id_caso)    ON DELETE RESTRICT,
    CONSTRAINT fk_remisiones_abogado FOREIGN KEY (id_abogado) REFERENCES abogados (id_abogado) ON DELETE RESTRICT
);
-- Regla de negocio: un caso puede remitirse a varios abogados (si uno rechaza, se envía a otro),
-- pero solo UNO puede aceptarlo. Índice único parcial = restricción declarativa, sin trigger.
CREATE UNIQUE INDEX uq_remisiones_una_aceptada ON remisiones (id_caso) WHERE estado_remision = 'ACEPTADA';

COMMENT ON TABLE  remisiones IS 'Envío de un caso a un abogado; unidad de facturación del negocio (cuota fija por caso remitido).';
COMMENT ON COLUMN remisiones.id_remision IS 'Identificador único de la remisión.';
COMMENT ON COLUMN remisiones.id_caso IS 'Caso remitido.';
COMMENT ON COLUMN remisiones.id_abogado IS 'Abogado que recibe el caso (no se repite el mismo abogado para el mismo caso).';
COMMENT ON COLUMN remisiones.fecha_envio IS 'Momento del envío.';
COMMENT ON COLUMN remisiones.estado_remision IS 'ENVIADA, ACEPTADA, RECHAZADA o VENCIDA. Solo una ACEPTADA por caso.';
COMMENT ON COLUMN remisiones.fecha_respuesta IS 'Momento en que el abogado aceptó o rechazó (nulo si no ha respondido).';
COMMENT ON COLUMN remisiones.motivo_rechazo IS 'Motivo dado por el abogado al rechazar.';
COMMENT ON COLUMN remisiones.valor_cobrado IS 'Valor en pesos colombianos (COP) cobrado al abogado por el caso remitido.';
