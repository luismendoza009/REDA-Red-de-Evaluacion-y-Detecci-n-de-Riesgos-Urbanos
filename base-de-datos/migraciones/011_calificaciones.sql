-- =============================================================================
-- 011_calificaciones.sql
-- El ciudadano califica al abogado que llevó su caso (1 a 5 estrellas y un comentario
-- opcional). Le da al siguiente ciudadano información para elegir con confianza.
-- Reglas: una calificación por caso, solo del ciudadano dueño del caso y solo sobre el
-- abogado asignado. Que el caso esté cerrado lo valida la aplicación (es una regla sobre
-- otra tabla); la base garantiza el resto.
-- El promedio NO se guarda: es un dato derivado (3FN); se calcula con AVG al consultar.
-- =============================================================================

CREATE TABLE calificaciones (
    id_calificacion  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_caso          INT          NOT NULL,
    id_abogado       INT          NOT NULL,
    puntaje          SMALLINT     NOT NULL,
    comentario       TEXT,
    fecha            TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_calificaciones_caso UNIQUE (id_caso),
    CONSTRAINT ck_calificaciones_puntaje CHECK (puntaje BETWEEN 1 AND 5),
    CONSTRAINT ck_calificaciones_comentario CHECK (comentario IS NULL OR length(trim(comentario)) BETWEEN 3 AND 1000),
    -- RESTRICT: la reputación de un abogado no debe desaparecer si alguien intenta borrar el caso
    CONSTRAINT fk_calificaciones_caso    FOREIGN KEY (id_caso)    REFERENCES casos    (id_caso)    ON DELETE RESTRICT,
    CONSTRAINT fk_calificaciones_abogado FOREIGN KEY (id_abogado) REFERENCES abogados (id_abogado) ON DELETE RESTRICT
);
-- la reputación se consulta por abogado (promedio, número y últimos comentarios)
CREATE INDEX ix_calificaciones_abogado ON calificaciones (id_abogado, fecha DESC);

COMMENT ON TABLE  calificaciones IS 'Calificación que el ciudadano da al abogado que llevó su caso (una por caso).';
COMMENT ON COLUMN calificaciones.id_calificacion IS 'Identificador único de la calificación.';
COMMENT ON COLUMN calificaciones.id_caso IS 'Caso calificado (UNIQUE: una calificación por caso). El autor es el dueño del caso.';
COMMENT ON COLUMN calificaciones.id_abogado IS 'Abogado calificado: el que el ciudadano eligió para el caso.';
COMMENT ON COLUMN calificaciones.puntaje IS 'De 1 (muy malo) a 5 (excelente) estrellas.';
COMMENT ON COLUMN calificaciones.comentario IS 'Por qué de la calificación (opcional). Se muestra a otros ciudadanos sin el nombre del autor.';
COMMENT ON COLUMN calificaciones.fecha IS 'Momento de la calificación.';

-- Reputación de cada abogado, lista para mostrar al ciudadano que compara postulaciones.
CREATE VIEW v_reputacion_abogados AS
SELECT a.id_abogado,
       count(c.id_calificacion)                AS num_calificaciones,
       round(avg(c.puntaje), 1)                AS promedio,
       count(*) FILTER (WHERE c.puntaje >= 4)  AS positivas
FROM abogados a
LEFT JOIN calificaciones c ON c.id_abogado = a.id_abogado
GROUP BY a.id_abogado;

COMMENT ON VIEW v_reputacion_abogados IS 'Promedio y número de calificaciones por abogado (calculado, no almacenado).';
