-- =============================================================================
-- 010_postulaciones_y_cuentas.sql
-- 1. El ciudadano ELIGE a su abogado: varios abogados se postulan a un caso y el
--    ciudadano escoge uno. Antes, el operador remitía el caso a un abogado.
-- 2. Perfil público del abogado (para que el ciudadano pueda comparar).
-- 3. Recuperación de contraseña con tokens de un solo uso.
-- No modifica tablas de forma incompatible: solo agrega tablas y columnas opcionales.
-- =============================================================================

-- ---------------------------------------------------------------- perfil del abogado
ALTER TABLE abogados
    ADD COLUMN anios_experiencia SMALLINT NOT NULL DEFAULT 0,
    ADD COLUMN presentacion      TEXT,
    ADD CONSTRAINT ck_abogados_experiencia CHECK (anios_experiencia BETWEEN 0 AND 70);
COMMENT ON COLUMN abogados.anios_experiencia IS 'Años de ejercicio declarados por el abogado (se muestran al ciudadano al comparar).';
COMMENT ON COLUMN abogados.presentacion IS 'Texto con que el abogado se presenta a los ciudadanos.';
COMMENT ON COLUMN abogados.activo IS 'false = pendiente de verificación de la tarjeta profesional o suspendido: no ve ni toma casos.';

-- ---------------------------------------------------------------- consentimiento del caso
ALTER TABLE casos ADD COLUMN fecha_consentimiento TIMESTAMPTZ;
COMMENT ON COLUMN casos.fecha_consentimiento IS 'Momento en que el ciudadano autorizó mostrar un resumen anónimo de su caso a los abogados aliados.';
COMMENT ON COLUMN casos.id_operador IS 'Operador que validó el incidente del que nace el caso.';

-- ---------------------------------------------------------------- postulaciones
-- Un abogado se postula a un caso con un mensaje; el ciudadano elige una postulación.
-- La elección crea la remisión ACEPTADA (lo que se factura) y cierra las demás postulaciones.
CREATE TABLE postulaciones (
    id_postulacion     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_caso            INT          NOT NULL,
    id_abogado         INT          NOT NULL,
    mensaje            TEXT         NOT NULL,
    estado             VARCHAR(12)  NOT NULL DEFAULT 'PENDIENTE',
    fecha_postulacion  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    fecha_resolucion   TIMESTAMPTZ,
    CONSTRAINT uq_postulaciones_caso_abogado UNIQUE (id_caso, id_abogado),
    CONSTRAINT ck_postulaciones_estado CHECK (estado IN ('PENDIENTE', 'ELEGIDA', 'NO_ELEGIDA', 'RETIRADA')),
    CONSTRAINT ck_postulaciones_mensaje CHECK (length(trim(mensaje)) >= 20),
    -- una postulación resuelta tiene fecha de resolución y una pendiente no
    CONSTRAINT ck_postulaciones_resolucion CHECK (
        (estado = 'PENDIENTE' AND fecha_resolucion IS NULL) OR
        (estado <> 'PENDIENTE' AND fecha_resolucion IS NOT NULL AND fecha_resolucion >= fecha_postulacion)),
    CONSTRAINT fk_postulaciones_caso    FOREIGN KEY (id_caso)    REFERENCES casos    (id_caso)    ON DELETE CASCADE,
    CONSTRAINT fk_postulaciones_abogado FOREIGN KEY (id_abogado) REFERENCES abogados (id_abogado) ON DELETE RESTRICT
);
-- el ciudadano elige a UN solo abogado por caso
CREATE UNIQUE INDEX uq_postulaciones_una_elegida ON postulaciones (id_caso) WHERE estado = 'ELEGIDA';
CREATE INDEX ix_postulaciones_abogado ON postulaciones (id_abogado);

COMMENT ON TABLE  postulaciones IS 'Interés de un abogado en tomar un caso. El ciudadano compara las postulaciones y elige una.';
COMMENT ON COLUMN postulaciones.id_postulacion IS 'Identificador único de la postulación.';
COMMENT ON COLUMN postulaciones.id_caso IS 'Caso al que se postula el abogado.';
COMMENT ON COLUMN postulaciones.id_abogado IS 'Abogado que se postula (no puede postularse dos veces al mismo caso).';
COMMENT ON COLUMN postulaciones.mensaje IS 'Por qué el abogado quiere el caso y cómo lo llevaría (mínimo 20 caracteres).';
COMMENT ON COLUMN postulaciones.estado IS 'PENDIENTE, ELEGIDA (el ciudadano lo escogió), NO_ELEGIDA (escogió a otro) o RETIRADA (el abogado desistió).';
COMMENT ON COLUMN postulaciones.fecha_postulacion IS 'Momento de la postulación.';
COMMENT ON COLUMN postulaciones.fecha_resolucion IS 'Momento en que la postulación dejó de estar pendiente.';

-- ---------------------------------------------------------------- recuperación de contraseña
-- Se guarda el HASH del token, nunca el token: si alguien lee la tabla no puede usarlo.
CREATE TABLE tokens_recuperacion (
    id_token          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario        INT          NOT NULL,
    hash_token        CHAR(64)     NOT NULL,
    fecha_creacion    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    fecha_expiracion  TIMESTAMPTZ  NOT NULL,
    fecha_uso         TIMESTAMPTZ,
    CONSTRAINT uq_tokens_hash UNIQUE (hash_token),
    CONSTRAINT ck_tokens_hash CHECK (hash_token ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_tokens_vigencia CHECK (fecha_expiracion > fecha_creacion),
    CONSTRAINT ck_tokens_uso CHECK (fecha_uso IS NULL OR fecha_uso BETWEEN fecha_creacion AND fecha_expiracion),
    CONSTRAINT fk_tokens_usuario FOREIGN KEY (id_usuario) REFERENCES usuarios (id_usuario) ON DELETE CASCADE
);
CREATE INDEX ix_tokens_usuario ON tokens_recuperacion (id_usuario);

COMMENT ON TABLE  tokens_recuperacion IS 'Enlaces de un solo uso para restablecer la contraseña (vencen a los 30 minutos).';
COMMENT ON COLUMN tokens_recuperacion.id_token IS 'Identificador único del token.';
COMMENT ON COLUMN tokens_recuperacion.id_usuario IS 'Usuario que pidió restablecer su contraseña.';
COMMENT ON COLUMN tokens_recuperacion.hash_token IS 'SHA-256 del token enviado por correo. Protección: el token en claro nunca se guarda.';
COMMENT ON COLUMN tokens_recuperacion.fecha_creacion IS 'Momento de la solicitud.';
COMMENT ON COLUMN tokens_recuperacion.fecha_expiracion IS 'Después de este momento el enlace ya no sirve.';
COMMENT ON COLUMN tokens_recuperacion.fecha_uso IS 'Momento en que se usó (nulo si no se ha usado). Un token usado no vuelve a servir.';
