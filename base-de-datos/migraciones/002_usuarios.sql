-- Cambio respecto a la Entrega 1: fecha_registro pasa a TIMESTAMPTZ, se agregan
-- activo y el registro del consentimiento de tratamiento de datos (Habeas Data).
CREATE TABLE usuarios (
    id_usuario            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre                VARCHAR(120) NOT NULL,
    correo                VARCHAR(150) NOT NULL,
    password_hash         VARCHAR(255) NOT NULL,
    id_rol                INT          NOT NULL,
    fecha_registro        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    activo                BOOLEAN      NOT NULL DEFAULT true,
    fecha_consentimiento  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_usuarios_correo UNIQUE (correo),
    -- correo normalizado en minúsculas: evita dos cuentas "Ana@x.com" y "ana@x.com"
    CONSTRAINT ck_usuarios_correo CHECK (correo = lower(correo) AND correo LIKE '%_@_%._%'),
    -- un hash BCrypt mide 60 caracteres; rechaza contraseñas guardadas en texto plano
    CONSTRAINT ck_usuarios_hash CHECK (password_hash LIKE '$2_$%' AND length(password_hash) = 60),
    CONSTRAINT fk_usuarios_rol FOREIGN KEY (id_rol) REFERENCES roles (id_rol) ON DELETE RESTRICT
);
COMMENT ON TABLE  usuarios IS 'Personas registradas en la plataforma (ciudadanos, operadores, abogados, administradores).';
COMMENT ON COLUMN usuarios.id_usuario IS 'Identificador único del usuario.';
COMMENT ON COLUMN usuarios.nombre IS '[PERSONAL] Nombre completo. Protección: no se expone en vistas públicas ni al rol de análisis.';
COMMENT ON COLUMN usuarios.correo IS '[PERSONAL] Correo electrónico en minúsculas, único; usado para autenticación. Protección: oculto en vistas públicas.';
COMMENT ON COLUMN usuarios.password_hash IS 'Hash BCrypt de la contraseña (nunca texto plano). Protección: ningún rol de lectura tiene acceso.';
COMMENT ON COLUMN usuarios.id_rol IS 'Rol de la aplicación asignado al usuario.';
COMMENT ON COLUMN usuarios.fecha_registro IS 'Momento de creación de la cuenta.';
COMMENT ON COLUMN usuarios.activo IS 'false = cuenta desactivada (no se borra: sus reportes son evidencia histórica).';
COMMENT ON COLUMN usuarios.fecha_consentimiento IS 'Momento en que el usuario aceptó la política de tratamiento de datos (Ley 1581 de 2012).';

-- Especialización 1:1 de usuarios con rol ABOGADO.
-- Se separa en otra tabla porque tarjeta_profesional, especialidad, etc. solo aplican
-- a abogados: dejarlas en usuarios obligaría a columnas nulas para todos los demás.
CREATE TABLE abogados (
    id_abogado            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario            INT          NOT NULL,
    tarjeta_profesional   VARCHAR(20)  NOT NULL,
    especialidad          VARCHAR(80)  NOT NULL,
    ciudad                VARCHAR(80)  NOT NULL DEFAULT 'Valledupar',
    activo                BOOLEAN      NOT NULL DEFAULT true,
    CONSTRAINT uq_abogados_usuario UNIQUE (id_usuario),
    CONSTRAINT uq_abogados_tarjeta UNIQUE (tarjeta_profesional),
    CONSTRAINT ck_abogados_tarjeta CHECK (tarjeta_profesional ~ '^[0-9]{4,10}$'),
    CONSTRAINT fk_abogados_usuario FOREIGN KEY (id_usuario) REFERENCES usuarios (id_usuario) ON DELETE RESTRICT
);
COMMENT ON TABLE  abogados IS 'Abogados o firmas aliadas que reciben casos remitidos (especialización 1:1 de usuarios).';
COMMENT ON COLUMN abogados.id_abogado IS 'Identificador único del abogado.';
COMMENT ON COLUMN abogados.id_usuario IS 'Cuenta de usuario del abogado (relación 1:1, UNIQUE).';
COMMENT ON COLUMN abogados.tarjeta_profesional IS '[PERSONAL] Número de tarjeta profesional (solo dígitos, único).';
COMMENT ON COLUMN abogados.especialidad IS 'Área de práctica (p. ej. responsabilidad del Estado, derecho administrativo).';
COMMENT ON COLUMN abogados.ciudad IS 'Ciudad donde ejerce; se usa para asignar casos.';
COMMENT ON COLUMN abogados.activo IS 'false = no recibe nuevas remisiones.';
