-- Notificaciones privadas para que el autor conozca los cambios de estado de sus reportes.
CREATE TABLE notificaciones (
    id_notificacion  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario       INT          NOT NULL,
    id_historial     INT          NOT NULL,
    fecha_creacion   DATE         NOT NULL DEFAULT CURRENT_DATE,
    fecha_lectura    DATE,
    CONSTRAINT uq_notificaciones_usuario_historial UNIQUE (id_usuario, id_historial),
    CONSTRAINT fk_notificaciones_usuario
        FOREIGN KEY (id_usuario) REFERENCES usuarios (id_usuario) ON DELETE CASCADE,
    CONSTRAINT fk_notificaciones_historial
        FOREIGN KEY (id_historial) REFERENCES historial_estados (id_historial) ON DELETE CASCADE
);

CREATE INDEX ix_notificaciones_usuario_recientes
    ON notificaciones (id_usuario, fecha_creacion DESC);

CREATE INDEX ix_notificaciones_no_leidas
    ON notificaciones (id_usuario)
    WHERE fecha_lectura IS NULL;

COMMENT ON TABLE notificaciones IS 'Avisos privados al autor cuando cambia el estado de uno de sus reportes.';
COMMENT ON COLUMN notificaciones.id_usuario IS 'Ciudadano destinatario de la notificación.';
COMMENT ON COLUMN notificaciones.id_historial IS 'Cambio de estado que originó el aviso.';
COMMENT ON COLUMN notificaciones.fecha_creacion IS 'Día en que se generó la notificación.';
COMMENT ON COLUMN notificaciones.fecha_lectura IS 'Día en que el ciudadano la marcó como leída; NULL indica pendiente.';
